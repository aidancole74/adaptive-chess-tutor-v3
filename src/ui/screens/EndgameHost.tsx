/** Endgame library: browse tablebase-verified positions by concept and practise any format directly. */
import { useEffect, useMemo, useState, type ReactElement } from 'react';
import { useApp } from '../store';
import { getEndgames } from '../../content/registry';
import { CONCEPTS, conceptName } from '../../curriculum/concepts';
import { buildEgBestMove, buildEgPlayout, buildEgWinOrDraw } from '../../exercises/endgames';
import type { EndgameItem } from '../../content/types';
import type { Exercise } from '../../exercises/types';
import { ExerciseView } from '../ExerciseView';
import { mastery } from '../../model/learner';

export default function EndgameHost(): ReactElement {
  const { settings, learner, recordStandalone } = useApp();
  const [items, setItems] = useState<EndgameItem[] | null>(null);
  const [concept, setConcept] = useState<string | null>(null);
  const [ex, setEx] = useState<Exercise | null>(null);

  useEffect(() => {
    void getEndgames().load().then(setItems);
  }, []);

  const counts = useMemo(() => {
    const m = new Map<string, EndgameItem[]>();
    for (const it of items ?? []) (m.get(it.concept) ?? m.set(it.concept, []).get(it.concept)!).push(it);
    return m;
  }, [items]);

  if (items === null) return <p className="loading">Loading endgames…</p>;
  const defs = CONCEPTS.filter((c) => c.domain === 'endgames');

  if (ex) {
    return (
      <section>
        <button className="link" onClick={() => setEx(null)}>
          ← Back to the library
        </button>
        <ExerciseView exercise={ex} settings={settings} why="Chosen by you from the endgame library." onDone={(r) => recordStandalone(ex, r)} onNext={() => setEx(null)} nextLabel="Back to the library" />
      </section>
    );
  }

  const list = concept ? (counts.get(concept) ?? []) : [];
  return (
    <section className="endgames" data-testid="endgame-library">
      <h1>Endgame library</h1>
      <p>Every position was generated by script and checked against the Lichess 7-piece tablebase: results, winning or drawing moves and distance to mate are exact. Play-outs need a connection to the tablebase.</p>
      {items.length === 0 && <p role="status">The endgame pack is not available in this build.</p>}
      <div className="grid2">
        <ul className="game-list">
          {defs.map((d) => {
            const n = counts.get(d.id)?.length ?? 0;
            return (
              <li key={d.id}>
                <button className={concept === d.id ? 'selected' : ''} disabled={n === 0} onClick={() => setConcept(d.id)} data-testid={`eg-concept-${d.id.split('/')[2]}`}>
                  <strong>{d.name}</strong>&nbsp;<span className="muted small">
                    {n} positions · tier {d.tier} · mastery {Math.round(mastery(learner, d.id, Date.now()).value * 100)}%{n === 0 ? ' · none verified' : ''}
                  </span>
                </button>
              </li>
            );
          })}
        </ul>
        {concept && (
          <div className="pane">
            <h2>{conceptName(concept)}</h2>
            <ul className="mistake-list">
              {list.slice(0, 30).map((it, i) => (
                <li key={it.id} className="row">
                  <span>
                    #{i + 1} · {it.category === 'win' ? 'win' : it.category === 'draw' ? 'draw' : 'loss'} for the side to move{it.dtm !== null && it.category !== 'draw' ? `, mate in ${Math.ceil(Math.abs(it.dtm) / 2)}` : ''}
                    {it.onlyMove ? ' · only move' : ''}
                  </span>
                  <button onClick={() => setEx(buildEgBestMove(it))} data-testid={i === 0 ? 'eg-best' : undefined}>Best move</button>
                  <button onClick={() => setEx(buildEgWinOrDraw(it))}>Win or draw?</button>
                  {it.playoutTarget !== null && <button onClick={() => setEx(buildEgPlayout(it))}>Play it out</button>}
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>
    </section>
  );
}
